import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
const manifest = JSON.parse(fs.readFileSync(path.join(root, "apps/docs/coverage-manifest.json"), "utf8")).coverage;
const destination = path.join(root, "apps/docs/content/docs/reference/generated-workflows.mdx");
const rows = (items) => items.map((item) => `| \`${item}\` | Public contract |`).join("\n");
const output = `---
title: Generated workflow contract
description: Generated inventory of public workflow APIs covered by Dyrected documentation.
---

{/* Generated by scripts/generate-workflow-reference.mjs. Do not edit manually. */}

## Workflow exports

| Export | Stability |
|---|---|
${rows(manifest.workflows)}

## Lifecycle event exports

| Export | Stability |
|---|---|
${rows(manifest.lifecycleEvents)}

## SDK methods

| Method | Stability |
|---|---|
${rows(manifest.sdkMethods)}

## REST endpoints

| Endpoint | Stability |
|---|---|
${rows(manifest.restApiEndpoints)}
`;

if (process.argv.includes("--check")) {
  const current = fs.existsSync(destination) ? fs.readFileSync(destination, "utf8") : "";
  if (current !== output) {
    console.error("Generated workflow reference is stale. Run pnpm --dir apps/docs docs:generate.");
    process.exit(1);
  }
} else {
  fs.writeFileSync(destination, output);
}
